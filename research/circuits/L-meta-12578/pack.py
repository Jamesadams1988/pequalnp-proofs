"""Rebuild the one-import refutation from a pinned upstream checkout and the local bridge.

Usage: python3 pack.py UPSTREAM_CHECKOUT Structure.lean statement.txt OUTPUT.lean
"""
import argparse
import hashlib
from pathlib import Path
import subprocess

REVISION = "60be64c28412eaf170ca324320dcefd2a44d0346"
ROW = "PEqualNP.Outside.L_meta_12578"
BRIDGE_SHA256 = "3ac3e0551329d1bd78f8599d35dd385402450c7956a9db915b942302ecac773c"


def upstream_source(checkout, number):
    source = f"lean/PEqualNP/Outside/L_meta_{number}.lean"
    return subprocess.check_output(
        ["git", "-C", str(checkout), "show", f"{REVISION}:{source}"], text=True
    )


def build(checkout, bridge_path, statement_path):
    orig = "PEqualNP.Outside.L_meta_"
    import_line = "import PEqualNP.Defs\n"
    core = upstream_source(checkout, 8683)
    if not core.startswith(import_line):
        raise ValueError("Unexpected imports in the pinned core proof")
    core = core[len(import_line):].replace(orig + "8683", ROW + ".Core")
    # q115 saves a gate under restriction. q183 and q184 prove wire relabelling.
    pin = upstream_source(checkout, 12433)
    pin = pin[pin.index("namespace "):pin.index("lemma yn {")]
    pin = pin.replace(orig + "12433", ROW + ".Pin") + f"end {ROW}.Pin\n"
    bridge = bridge_path.read_bytes()
    if hashlib.sha256(bridge).hexdigest() != BRIDGE_SHA256:
        raise ValueError("Expected the verified Structure.lean at the documented revision")
    bridge = bridge.decode().split("/-!", 1)[1]
    bridge = "/-!" + bridge.replace("Split12578.Bridge", ROW + ".Bridge")
    start_open = bridge.index("open PEqualNP.MetaComplexity.Helpers\n")
    end_open = bridge.index("\nabbrev BFn", start_open)
    bridge = bridge[:start_open] + f"open {ROW}.Pin\n" + bridge[end_open:]
    for a, b in (("relGate","jt"), ("ofFn_snoc","q134"), ("rel_fold","q184"),
                 ("rel_init","q183"), (orig+"8683", ROW+".Core")):
        bridge = bridge.replace(a, b)
    start = bridge.index("  cases s with\n")
    end = bridge.index("\n/-- For this table", start)
    bridge = bridge[:start] + """  have hdep := depends (Fin.last 5) (Or.inr rfl)
  have hnc : ∃ y y' : Fin 5 → Bool, six (Fin.snoc y true) ≠ six (Fin.snoc y' true) := by decide
  obtain ⟨t, ht, reduced⟩ := q115 5 six true s hdep hnc h
  rw [pin] at reduced
  exact ⟨t, ht, reduced⟩
""" + bridge[end:]
    credits = f"""
/-!
Proof of the opposite of row 12578 by splitting the last bit of the five-input row 8683.
Generated by pack.py from brilliant-hq/pequalnp-proofs at {REVISION}, Apache-2.0.
Research by James Adams (Jamesadams1988). Core reproduces Julleht's L_meta_8683.
Pin reproduces the restriction and relabelling prefix of k-sandhu's L_meta_12433.
Original source credits are retained. Bridge uses the structural proof in Structure.lean.
-/
"""
    stmt = statement_path.read_text().strip()
    if hashlib.sha256(stmt.encode()).hexdigest() != "eff8d09303f0f64e49fb0051a255d3c1426ee3f11016b9a49c4301a63d914936":
        raise ValueError("Expected the posted L-meta-12578 statement")
    wrapper = f"theorem {ROW} : ¬ ({stmt}) :=\n  fun submitted => submitted {ROW}.Bridge.positive\n"
    return "\n".join((import_line, credits, core, pin, bridge, wrapper))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("checkout","bridge","statement","output"):
        parser.add_argument(name, type=Path)
    args = parser.parse_args()
    args.output.write_text(build(args.checkout,args.bridge,args.statement))
